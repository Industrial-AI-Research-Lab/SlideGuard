"""
Ablation 2: Text-only evaluation (no multimodal input).

Subclasses SlideGuardEvaluator so that non-service slide criteria receive
the textual slide description generated by the service phase instead of the
raw slide image.  Service criteria (slide_type, slide_description) still
operate on images — only evaluation criteria are affected.
"""

import asyncio
import logging
from textwrap import dedent
from typing import Any, AsyncIterable, Dict, List, Optional, Tuple

from pydantic import BaseModel
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.runnables import RunnableConfig

from slideguard.crew.evaluator import (
    EvaluationState,
    NotApplicableResult,
    SlideGuardEvaluator,
)
from slideguard.criteria.base import CriterionInfo
from slideguard.criteria.presentation_types import PresentationType
from slideguard.schemes import Criteria, Slideable

logger = logging.getLogger(__name__)

TEXT_ONLY_SLIDE_TASK_PROMPT = dedent("""\
    Analyze this slide based on its textual description.

    Slide title: {slide_title}
    Slide content: {slide_description}
    Slide summary: {slide_summary}
""")


class SlideTextInput(Slideable):
    """Cache-compatible input carrying text instead of an image path."""
    slide_title: str
    slide_description: str
    slide_summary: str

    class Config:
        frozen = True


class _TextDeck(BaseModel):
    """Thin wrapper so _eval_text_criterion can iterate .slides."""
    slide_deck_path: str
    slides: List[SlideTextInput]


class TextOnlyEvaluator(SlideGuardEvaluator):
    """Evaluator that feeds slide *descriptions* (text) to evaluation criteria
    instead of slide images (multimodal)."""

    def _make_slide_criterion_node(self, crit: Criteria):
        async def _run(state: EvaluationState, config: RunnableConfig) -> Dict[str, Any]:
            if not state.slides or crit not in state.slide_criterias:
                return {}

            registry = self._registry
            info = registry.get_info(crit)
            total = len(state.slides.slides)

            # --- applicability filtering (same as parent) ---
            needs_filtering = (
                info.applicable_slide_types
                or info.exclude_slide_types
                or info.requires_infographics
            )
            eligible = list(range(total))
            if needs_filtering:
                st_service = (state.slide_service or {}).get(Criteria.slide_type)
                if st_service and len(st_service) == total:
                    slide_types = [st_service[i].slide_type for i in range(total)]
                    eligible = [
                        i for i, types in enumerate(slide_types)
                        if self._criterion_applies(info, types, st_service[i].contains_infographics)
                    ]
                else:
                    eligible = list(range(total))

            if not eligible:
                return {"slide_results": {crit: [NotApplicableResult() for _ in range(total)]}}

            # --- build text inputs from service descriptions ---
            descs = (state.slide_service or {}).get(Criteria.slide_description, [])
            text_inputs: List[SlideTextInput] = []
            for i in eligible:
                desc = descs[i] if i < len(descs) else None
                text_inputs.append(SlideTextInput(
                    slide_id=state.slides.slides[i].slide_id,
                    slide_title=desc.title if desc else "",
                    slide_description=desc.description if desc else "",
                    slide_summary=desc.summary if desc else "",
                ))

            text_deck = _TextDeck(
                slide_deck_path=state.slides.slide_deck_path,
                slides=text_inputs,
            )

            # --- build text-based chain ---
            modified_info = info.model_copy(deep=True)
            modified_info.task_prompt_template = TEXT_ONLY_SLIDE_TASK_PROMPT
            chain = ChatPromptTemplate.from_messages([
                ("system", modified_info.get_agent_prompt(state.presentation_type)),
                ("user", TEXT_ONLY_SLIDE_TASK_PROMPT),
            ]) | self.llm.with_structured_output_retry(modified_info.pydantic)

            # --- evaluate with text payloads ---
            entities = await self._eval_text_criterion(
                info=modified_info,
                text_deck=text_deck,
                chain=chain,
                config=config,
                presentation_type=state.presentation_type,
            )

            if len(eligible) == total:
                processed = [self._postprocess_result(crit, r) for r in entities]
                return {"slide_results": {crit: processed}}

            merged: List[BaseModel] = [NotApplicableResult() for _ in range(total)]
            for j, idx in enumerate(eligible):
                merged[idx] = self._postprocess_result(crit, entities[j])
            return {"slide_results": {crit: merged}}

        return _run

    async def _eval_text_criterion(
        self,
        info: CriterionInfo,
        text_deck: _TextDeck,
        chain: Any,
        config: RunnableConfig,
        presentation_type: Optional[PresentationType] = None,
    ) -> List[BaseModel]:
        """Like _eval_criterion_with_cache but builds text-based payloads."""

        async def compute(inputs: List[Tuple[int, SlideTextInput]]) -> AsyncIterable[Tuple[int, BaseModel]]:
            async def _ainvoke_one(idx: int, payload: Dict[str, Any]) -> Tuple[int, BaseModel]:
                try:
                    out = await chain.ainvoke(payload, config)
                    p = out.pydantic
                    if p is None and out.json is not None:
                        try:
                            p = info.pydantic.model_validate(out.json)
                        except Exception:
                            p = None
                    if p is None:
                        p = self._create_fallback(info.pydantic)
                    return idx, p
                except Exception as e:
                    logger.warning("Text-only eval failed for %s idx=%s: %s", info.criteria.value, idx, e)
                    return idx, self._create_fallback(info.pydantic)

            payloads = [
                (i, {
                    "slide_title": inp.slide_title,
                    "slide_description": inp.slide_description,
                    "slide_summary": inp.slide_summary,
                })
                for i, inp in inputs
            ]
            coros = [_ainvoke_one(i, d) for i, d in payloads]
            for coro in asyncio.as_completed(coros):
                yield await coro

        try:
            criteria_id = info.criteria.value
            if presentation_type is not None:
                criteria_id = f"{criteria_id}_{presentation_type.value}"
            criteria_id = f"{criteria_id}_{self.llm.language.value}_textonly"

            entities = await self.cache_manager.compute_with_cache(
                deck_name=text_deck.slide_deck_path,
                criteria_id=criteria_id,
                inputs=text_deck.slides,
                func=compute,
            )
            if not entities or len(entities) != len(text_deck.slides):
                entities = [self._create_fallback(info.pydantic) for _ in text_deck.slides]
            return entities
        except Exception as e:
            logger.error("Cache computation error for %s: %s", info.criteria.value, e)
            return [self._create_fallback(info.pydantic) for _ in text_deck.slides]
